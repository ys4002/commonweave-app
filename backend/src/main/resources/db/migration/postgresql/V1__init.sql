CREATE TABLE IF NOT EXISTS commonweave_users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email VARCHAR(190) NOT NULL,
  password_hash VARCHAR(100) NOT NULL,
  display_name VARCHAR(80) NOT NULL,
  bio VARCHAR(500) NULL,
  locality VARCHAR(120) NULL,
  onboarded BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uq_commonweave_users_email UNIQUE (email)
);

CREATE TABLE IF NOT EXISTS circles (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  slug VARCHAR(120) NOT NULL,
  name VARCHAR(120) NOT NULL,
  city VARCHAR(80) NOT NULL,
  area VARCHAR(120) NOT NULL,
  description VARCHAR(1000) NULL,
  guidelines VARCHAR(2000) NULL,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uq_circles_slug UNIQUE (slug)
);

CREATE TABLE IF NOT EXISTS memberships (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  circle_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL,
  role VARCHAR(20) NOT NULL,
  status VARCHAR(20) NOT NULL,
  joined_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uq_memberships_circle_user UNIQUE (circle_id, user_id),
  CONSTRAINT fk_memberships_circle FOREIGN KEY (circle_id) REFERENCES circles (id),
  CONSTRAINT fk_memberships_user FOREIGN KEY (user_id) REFERENCES commonweave_users (id)
);
CREATE INDEX IF NOT EXISTS ix_memberships_user ON memberships (user_id, status);

CREATE TABLE IF NOT EXISTS listings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  circle_id BIGINT NOT NULL,
  owner_id BIGINT NOT NULL,
  type VARCHAR(10) NOT NULL,
  kind VARCHAR(10) NOT NULL,
  title VARCHAR(120) NOT NULL,
  description VARCHAR(2000) NULL,
  category VARCHAR(30) NOT NULL,
  tags VARCHAR(400) NULL,
  available_from DATE NOT NULL,
  available_to DATE NOT NULL,
  pickup_preference VARCHAR(200) NULL,
  estimated_value_inr INT NOT NULL DEFAULT 0,
  deposit_inr INT NOT NULL DEFAULT 0,
  hours_estimate INT NOT NULL DEFAULT 0,
  return_expected BOOLEAN NOT NULL DEFAULT FALSE,
  status VARCHAR(20) NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT fk_listings_circle FOREIGN KEY (circle_id) REFERENCES circles (id),
  CONSTRAINT fk_listings_owner FOREIGN KEY (owner_id) REFERENCES commonweave_users (id)
);
CREATE INDEX IF NOT EXISTS ix_listings_circle_status ON listings (circle_id, status, type);
CREATE INDEX IF NOT EXISTS ix_listings_owner ON listings (owner_id);

CREATE TABLE IF NOT EXISTS handoffs (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  listing_id BIGINT NOT NULL,
  circle_id BIGINT NOT NULL,
  provider_id BIGINT NOT NULL,
  recipient_id BIGINT NOT NULL,
  proposer_id BIGINT NOT NULL,
  status VARCHAR(20) NOT NULL,
  message VARCHAR(500) NULL,
  scheduled_at TIMESTAMP(6) NULL,
  pickup_note VARCHAR(500) NULL,
  return_by TIMESTAMP(6) NULL,
  return_expected BOOLEAN NOT NULL DEFAULT FALSE,
  created_at TIMESTAMP(6) NOT NULL,
  updated_at TIMESTAMP(6) NOT NULL,
  version BIGINT NOT NULL DEFAULT 0,
  active_listing_id BIGINT GENERATED ALWAYS AS (CASE WHEN status IN ('SCHEDULED','HANDED_OFF') THEN listing_id END) STORED,
  CONSTRAINT uq_handoffs_active_listing UNIQUE (active_listing_id),
  CONSTRAINT fk_handoffs_listing FOREIGN KEY (listing_id) REFERENCES listings (id),
  CONSTRAINT fk_handoffs_circle FOREIGN KEY (circle_id) REFERENCES circles (id),
  CONSTRAINT fk_handoffs_provider FOREIGN KEY (provider_id) REFERENCES commonweave_users (id),
  CONSTRAINT fk_handoffs_recipient FOREIGN KEY (recipient_id) REFERENCES commonweave_users (id),
  CONSTRAINT fk_handoffs_proposer FOREIGN KEY (proposer_id) REFERENCES commonweave_users (id)
);
CREATE INDEX IF NOT EXISTS ix_handoffs_listing ON handoffs (listing_id, status);
CREATE INDEX IF NOT EXISTS ix_handoffs_provider ON handoffs (provider_id, status);
CREATE INDEX IF NOT EXISTS ix_handoffs_recipient ON handoffs (recipient_id, status);
CREATE INDEX IF NOT EXISTS ix_handoffs_circle ON handoffs (circle_id, status, updated_at);

CREATE TABLE IF NOT EXISTS handoff_events (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  handoff_id BIGINT NOT NULL,
  actor_id BIGINT NOT NULL,
  from_status VARCHAR(20) NULL,
  to_status VARCHAR(20) NOT NULL,
  note VARCHAR(500) NULL,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT fk_events_handoff FOREIGN KEY (handoff_id) REFERENCES handoffs (id),
  CONSTRAINT fk_events_actor FOREIGN KEY (actor_id) REFERENCES commonweave_users (id)
);
CREATE INDEX IF NOT EXISTS ix_events_handoff ON handoff_events (handoff_id);

CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL,
  type VARCHAR(40) NOT NULL,
  title VARCHAR(160) NOT NULL,
  body VARCHAR(500) NULL,
  link VARCHAR(200) NULL,
  dedupe_key VARCHAR(120) NULL,
  read_at TIMESTAMP(6) NULL,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT uq_notifications_dedupe UNIQUE (user_id, dedupe_key),
  CONSTRAINT fk_notifications_user FOREIGN KEY (user_id) REFERENCES commonweave_users (id)
);
CREATE INDEX IF NOT EXISTS ix_notifications_user ON notifications (user_id, read_at, created_at);

CREATE TABLE IF NOT EXISTS reports (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  circle_id BIGINT NOT NULL,
  reporter_id BIGINT NOT NULL,
  target_type VARCHAR(10) NOT NULL,
  target_id BIGINT NOT NULL,
  reason VARCHAR(500) NOT NULL,
  status VARCHAR(12) NOT NULL,
  resolution_note VARCHAR(500) NULL,
  resolved_by BIGINT NULL,
  created_at TIMESTAMP(6) NOT NULL,
  resolved_at TIMESTAMP(6) NULL,
  CONSTRAINT fk_reports_circle FOREIGN KEY (circle_id) REFERENCES circles (id),
  CONSTRAINT fk_reports_reporter FOREIGN KEY (reporter_id) REFERENCES commonweave_users (id),
  CONSTRAINT fk_reports_resolver FOREIGN KEY (resolved_by) REFERENCES commonweave_users (id)
);
CREATE INDEX IF NOT EXISTS ix_reports_circle ON reports (circle_id, status, created_at);

CREATE TABLE IF NOT EXISTS moderation_actions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  circle_id BIGINT NOT NULL,
  moderator_id BIGINT NOT NULL,
  action_type VARCHAR(40) NOT NULL,
  target_type VARCHAR(10) NOT NULL,
  target_id BIGINT NOT NULL,
  note VARCHAR(500) NULL,
  created_at TIMESTAMP(6) NOT NULL,
  CONSTRAINT fk_modactions_circle FOREIGN KEY (circle_id) REFERENCES circles (id),
  CONSTRAINT fk_modactions_moderator FOREIGN KEY (moderator_id) REFERENCES commonweave_users (id)
);
CREATE INDEX IF NOT EXISTS ix_modactions_circle ON moderation_actions (circle_id, created_at);
